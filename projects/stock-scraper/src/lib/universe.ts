const bySymbol = new Map<string, StockMeta>();
for (const s of STOCK_UNIVERSE) {
  bySymbol.set(s.symbol, s);
}
export const UNIQUE_UNIVERSE: StockMeta[] = Array.from(bySymbol.values()).sort((a, b) =>
  a.symbol.localeCompare(b.symbol)
);

export function getStockMeta(symbol: string): StockMeta | undefined {
  return bySymbol.get(symbol.toUpperCase());
}

export function getAllSymbols(): string[] {
  return UNIQUE_UNIVERSE.map((s) => s.symbol);
}

